import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { API, SymbolFlags } from "typescript/unstable/sync";

// TypeScript 7's compiler service replaces the old in-process compiler API.
const api = new API({ cwd: process.cwd() });
try {
  const snapshot = api.updateSnapshot({ openProjects: [path.resolve("tsconfig.json")] });
  const project = snapshot.getProject(path.resolve("tsconfig.json"));
  if (!project) throw new Error("Cannot open TypeScript project.");
  const pkg = JSON.parse(readFileSync("package.json", "utf8")) as {
    name: string;
    exports: Record<string, string | { default: string }>;
  };
  const sections: string[] = [
    "# Public API",
    "Generated by `pnpm api:report`. Review changes to exported signatures.",
  ];
  for (const [entry, exported] of Object.entries(pkg.exports)) {
    // Compiled entry points are reported from their source.
    const file = typeof exported === "string" ? exported : exported.default;
    const target = file.replace(/^\.\/lib\/(.*)\.js$/, "./src/$1.ts");
    if (!target.endsWith(".ts")) continue;
    const source = project.program.getSourceFile(path.resolve(target));
    const module = source && project.checker.getSymbolAtLocation(source);
    if (!module) throw new Error(`Missing module: ${target}`);
    const signatures = project.checker
      .getExportsOfModule(module)
      .toSorted((a, b) => a.name.localeCompare(b.name))
      .map((exported) => {
        const symbol =
          exported.flags & SymbolFlags.Alias
            ? project.checker.getAliasedSymbol(exported)
            : exported;
        if (symbol.flags & (SymbolFlags.Function | SymbolFlags.Variable)) {
          const type = project.checker.getTypeOfSymbol(symbol);
          if (!type) throw new Error(`Missing type for ${symbol.name}`);
          return `export const ${exported.name}: ${project.checker.typeToString(type)};`;
        }
        return symbol.declarations.map((handle) => handle.resolve()?.getText() ?? "").join("\n");
      });
    sections.push(
      `## ${pkg.name}${entry === "." ? "" : entry.slice(1)}`,
      `\`\`\`ts\n${signatures.join("\n\n")}\n\`\`\``,
    );
  }
  const report = `${sections.join("\n\n")}\n`;
  const filename = "etc/api-report.md";
  if (process.argv.includes("--check")) {
    if (readFileSync(filename, "utf8") !== report)
      throw new Error("Public API report changed. Run pnpm api:report.");
  } else {
    mkdirSync("etc", { recursive: true });
    writeFileSync(filename, report);
  }
  snapshot.dispose();
} finally {
  api.close();
}
